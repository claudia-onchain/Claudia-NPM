#!/usr/bin/env node
// Writes the tool catalog (packages/sdk/src/tools) into the website repo as ONE dependency-free TypeScript file, so the
// online MCP server on useclaudia.xyz serves exactly the same tools, prompts, resources and views as @useclaudia/mcp.
// The website can't install npm packages (its lockfile comes from Replit's mirror), hence a generated copy.
//
//   node scripts/sync-catalog.mjs ../DexPumpzip/shared/mcpCatalog.ts
//   node scripts/sync-catalog.mjs --check ../DexPumpzip/shared/mcpCatalog.ts   (exit 1 when out of date)
//
// Re-run after every catalog change (and after merging) — the generated file must never be edited by hand.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "packages/sdk/src/tools");
// Dependency order: every file only uses what an earlier file declared.
const FILES = ["types.ts", "untrusted.ts", "catalog.ts", "prompts.ts", "resources.ts", "ui.ts", "handlers.ts", "convert.ts", "index.ts"];

const args = process.argv.slice(2);
const check = args.includes("--check");
const target = args.find((a) => !a.startsWith("--"));
if (!target) {
  console.error("usage: node scripts/sync-catalog.mjs [--check] <path to DexPumpzip/shared/mcpCatalog.ts>");
  process.exit(2);
}

const LOCAL_IMPORT = /^import\s+(type\s+)?\{[^}]*\}\s+from\s+"\.\/[^"]+";\s*$/;
const LOCAL_REEXPORT = /^export\s+(type\s+)?\{[^}]*\}\s+from\s+"\.\/[^"]+";\s*$/;

let body = "";
for (const f of FILES) {
  const text = readFileSync(join(src, f), "utf8");
  const lines = text.split("\n").filter((l) => !LOCAL_IMPORT.test(l) && !LOCAL_REEXPORT.test(l));
  if (lines.some((l) => /^\s*import\s/.test(l))) throw new Error(`${f}: only relative imports are allowed in the catalog (the website copy has no dependencies)`);
  body += `\n// ─── ${f} ${"─".repeat(Math.max(4, 60 - f.length))}\n` + lines.join("\n").trim() + "\n";
}

const sdkVersion = JSON.parse(readFileSync(join(root, "packages/sdk/package.json"), "utf8")).version;
const hash = createHash("sha256").update(body).digest("hex").slice(0, 16);
const out =
  `// GENERATED by claudia-sdk/scripts/sync-catalog.mjs from @useclaudia/sdk ${sdkVersion} (packages/sdk/src/tools).\n` +
  `// DO NOT EDIT: change the catalog in claudia-sdk and re-run the script. Catalog hash: ${hash}\n` +
  `/* eslint-disable */\n` +
  body;

const dest = resolve(process.cwd(), target);
if (check) {
  const cur = existsSync(dest) ? readFileSync(dest, "utf8") : "";
  if (cur !== out) {
    console.error(`${dest} is out of date (catalog ${hash}). Run: node scripts/sync-catalog.mjs ${target}`);
    process.exit(1);
  }
  console.log(`${dest} is up to date (catalog ${hash}).`);
} else {
  writeFileSync(dest, out);
  console.log(`wrote ${dest} (catalog ${hash}, ${out.length} bytes)`);
}
